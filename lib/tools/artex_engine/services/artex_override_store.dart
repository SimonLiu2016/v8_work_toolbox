import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:path/path.dart' as p;

import '../../../services/app_paths.dart';
import '../models/artex_engine_config.dart';

/// 本工具生成的 override 文件名。
const String kArtexOverrideFileName = 'docker-compose.override.yml';

/// 标记注释的首行。只有以它开头的文件才会被本工具重写；别的文件先备份
/// （task 4.2 / design D1 的「风险：用户手工编辑 override 被冲掉」）。
const String kArtexOverrideMarker = '# Generated by V8WorkToolbox ARTEX engine tool';

/// Override 文件的生成、读取与安全重写。
///
/// **为什么用 override 而不是改上游 `docker-compose.yml`**（design D1）：
/// spike 里直接改原文件验证过可行，但用户 `git pull` 一次就丢，且会让
/// artex 仓库出现本地未提交改动，干扰后续升级。override 是 compose 原生
/// 的「本地部署差异」机制，对上游零侵入。
class ArtexOverrideStore {
  ArtexOverrideStore._();
  static final ArtexOverrideStore instance = ArtexOverrideStore._();

  /// 生成 override 内容。
  ///
  /// 两件事：关门控（否则容器内绑 `:8787` 触发门控，`/api/health` 返回假
  /// nginx 页面，spike 实测）、按配置覆盖端口。
  ///
  /// `!override` 标签必须带：compose 对 `ports` 的默认合并行为是**追加**，
  /// 不带标签会导致 8787 同时绑两个端口（上游的 `"8787:8787"` 还在）。
  String render(ArtexEngineConfig config) {
    final buffer = StringBuffer()
      ..writeln(kArtexOverrideMarker)
      ..writeln('# 本文件由 V8WorkToolbox 的 ARTEX 引擎工具自动生成与维护。')
      ..writeln('# 手工修改会在下次启动时被覆盖；如需长期定制请改用上游')
      ..writeln('# docker-compose.yml，并把这个工具的门控/端口配置对齐。')
      ..writeln('# 详见 openspec/changes/add-artex-engine-toolbox/design.md D1。')
      ..writeln('services:')
      ..writeln('  artex:');

    if (config.gateOff) {
      buffer
        ..writeln('    environment:')
        ..writeln('      # 单机部署关门控：容器内绑 :8787 会被判定为非 loopback 而')
        ..writeln('      # 自动开启，导致健康探测拿到假 nginx 欢迎页（HTTP 200）。')
        ..writeln('      ARTEX_GATE: "off"');
    }

    buffer
      ..writeln('    ports: !override')
      ..writeln('      - "127.0.0.1:${config.httpPort}:8787"')
      ..writeln('      - "127.0.0.1:${config.proxyPort}:8788"');

    return buffer.toString();
  }

  /// override 文件路径。
  String pathFor(String projectDir) =>
      p.join(projectDir, kArtexOverrideFileName);

  /// 读取现有内容；不存在返回 null。
  String? read(String projectDir) {
    final file = File(pathFor(projectDir));
    if (!file.existsSync()) return null;
    try {
      return file.readAsStringSync();
    } catch (e) {
      debugPrint('[ArtexOverrideStore] 读取 override 失败: $e');
      return null;
    }
  }

  /// 该文件是否由本工具生成（可安全重写）。
  bool isManaged(String projectDir) {
    final content = read(projectDir);
    if (content == null) return false;
    return content.trimLeft().startsWith(kArtexOverrideMarker);
  }

  /// 写入 override。
  ///
  /// 返回是否发生了备份（调用方需告知用户——非本工具生成的文件被替换是
  /// 意外情况，静默覆盖违反 design D1 的风险缓解承诺）。
  bool write(String projectDir, ArtexEngineConfig config) {
    final file = File(pathFor(projectDir));
    var backedUp = false;

    if (file.existsSync() && !isManaged(projectDir)) {
      final backup = File(
        p.join(
          AppPaths.artexDir.path,
          '$kArtexOverrideFileName.bak-${DateTime.now().millisecondsSinceEpoch}',
        ),
      );
      try {
        AppPaths.artexDir.createSync(recursive: true);
        file.copySync(backup.path);
        backedUp = true;
        debugPrint('[ArtexOverrideStore] 已备份非托管 override → ${backup.path}');
      } catch (e) {
        debugPrint('[ArtexOverrideStore] 备份失败（仍继续写入）: $e');
      }
    }

    file.writeAsStringSync(render(config));
    return backedUp;
  }

  /// 删除 override（回滚用）。仅删除本工具生成的那份。
  bool remove(String projectDir) {
    final file = File(pathFor(projectDir));
    if (!file.existsSync()) return false;
    if (!isManaged(projectDir)) return false;
    try {
      file.deleteSync();
      return true;
    } on FileSystemException catch (e) {
      debugPrint('[ArtexOverrideStore] 删除 override 失败: $e');
      return false;
    }
  }
}
